/**
 * Generates a migration for house styles added to styles/*.yaml AFTER a seed
 * migration already shipped. Reads every style, skips slugs any existing
 * migration already inserts, writes the remainder into the target file.
 * Run from the repo root:  node web/scripts/gen-style-migration.mjs 0011_styles.sql
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { listStyles } from '../../src/style-fs.ts';

const target = process.argv[2];
if (!target) {
  console.error('usage: node web/scripts/gen-style-migration.mjs <NNNN_name.sql>');
  process.exit(2);
}

const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replaceAll("'", "''")}'`);
const now = new Date().toISOString();
const T_HOUSE = 'seed_team_house';

// Every slug already inserted by an existing migration is off the list.
const seeded = new Set();
for (const f of await readdir('web/migrations')) {
  if (f === target) continue;
  const sql = await readFile(`web/migrations/${f}`, 'utf8');
  for (const m of sql.matchAll(/seed_style_([a-z0-9_]+)/g)) seeded.add(m[1]);
}

const lines = [`-- ${target.replace('.sql', '')} — generated by web/scripts/gen-style-migration.mjs. Do not edit by hand.`, ''];
let n = 0;
for (const s of await listStyles()) {
  const idSlug = s.slug.replaceAll('-', '_');
  if (seeded.has(idSlug)) continue;
  n++;
  lines.push(
    `INSERT INTO style (id, team_id, slug, name, description, look, subject, avoid, tags, origin, created_at, updated_at)` +
      ` VALUES (${q('seed_style_' + idSlug)}, ${q(T_HOUSE)}, ${q(s.slug)}, ${q(s.name)}, ${q(s.description)},` +
      ` ${q(s.look)}, ${q(s.subject)}, ${q(s.avoid)}, ${q(JSON.stringify(s.tags))}, ${q(s.origin)}, ${q(now)}, ${q(now)});`,
  );
}

await writeFile(`web/migrations/${target}`, lines.join('\n') + '\n');
console.log(`${target} written: ${n} new house styles`);
